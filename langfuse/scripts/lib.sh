#!/usr/bin/env bash
# Shared by the langfuse scripts (sourced, never run): paths, the address and the key generation. Run them from the repo root.
# shellcheck disable=SC2034
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$root"
compose=(docker compose -f langfuse/compose.yaml --env-file .env)
port=3290
url="http://localhost:$port"

# Appends the Langfuse values missing from .env, generated once with openssl; never overwrites a value.
ensure_env() {
  [ -f .env ] || touch .env
  local added=0 name value
  add() {
    name="$1"
    value="$2"
    if ! grep -q "^$name=" .env; then
      if [ "$added" -eq 0 ]; then
        [ -z "$(tail -c1 .env)" ] || echo >>.env
        echo "# Local Langfuse (langfuse/compose.yaml), generated by langfuse/scripts/up.sh" >>.env
      fi
      echo "$name=$value" >>.env
      added=1
      echo "generated $name in .env"
    fi
  }
  add LANGFUSE_PUBLIC_KEY "pk-lf-$(openssl rand -hex 16)"
  add LANGFUSE_SECRET_KEY "sk-lf-$(openssl rand -hex 16)"
  add LANGFUSE_USER_EMAIL "suwexag@example.com"
  add LANGFUSE_USER_PASSWORD "$(openssl rand -hex 12)"
  add LANGFUSE_NEXTAUTH_SECRET "$(openssl rand -hex 32)"
  add LANGFUSE_SALT "$(openssl rand -hex 32)"
  add LANGFUSE_ENCRYPTION_KEY "$(openssl rand -hex 32)"
  add LANGFUSE_POSTGRES_PASSWORD "$(openssl rand -hex 16)"
  add LANGFUSE_CLICKHOUSE_PASSWORD "$(openssl rand -hex 16)"
  add LANGFUSE_MINIO_PASSWORD "$(openssl rand -hex 16)"
  add LANGFUSE_REDIS_PASSWORD "$(openssl rand -hex 16)"
}

# The value of a name in .env (empty when missing).
env_value() {
  grep -m1 "^$1=" .env | cut -d= -f2- || true
}

healthy() {
  curl -fsS -m 3 "$url/api/public/health" >/dev/null 2>&1
}

# Creates, through the public API with the project keys, the model definition of the agent's model (a local model: prices 0) so its
# generations get a model and their tokens show without warnings. Skipped when OPENAI_MODEL is not set or the definition exists.
ensure_model() {
  local model auth page=1 pages=1 body escaped
  model="$(env_value OPENAI_MODEL)"
  if [ -z "$model" ]; then
    echo "model definition: skipped (OPENAI_MODEL is not set in .env)"
    return 0
  fi
  auth="$(env_value LANGFUSE_PUBLIC_KEY):$(env_value LANGFUSE_SECRET_KEY)"
  while [ "$page" -le "$pages" ]; do
    body="$(curl -fsS -m 20 -u "$auth" "$url/api/public/models?limit=100&page=$page")"
    if jq -e --arg m "$model" '.data[] | select(.modelName == $m and (.isLangfuseManaged | not))' <<<"$body" >/dev/null; then
      echo "model definition: $model exists"
      return 0
    fi
    pages="$(jq -r '.meta.totalPages' <<<"$body")"
    page=$((page + 1))
  done
  escaped="$(printf '%s' "$model" | sed 's/[][\.*^$+?(){}|]/\\&/g')"
  jq -n --arg m "$model" --arg p "(?i)^$escaped\$" '{modelName: $m, matchPattern: $p, unit: "TOKENS", inputPrice: 0, outputPrice: 0}' |
    curl -fsS -m 20 -u "$auth" -H 'content-type: application/json' -d @- "$url/api/public/models" >/dev/null
  echo "model definition: created $model (prices 0)"
}
